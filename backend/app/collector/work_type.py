"""사업유형(개발/운영/유지보수/구축 등) 제목 기반 근사 추정 — 2026-09-01 요청.

첨부 규격서까지 봐야 정확해지는 건 S8 심층분석의 몫이다. 여기는 L1/L2와 같은 이유로
전체 공고에 자동으로 돌아야 하는 가벼운 1차 추정치일 뿐이라, 오판 가능성을 안고 쓴다 —
정확한 값이 필요하면 S8을 돌려야 한다.
"""

from __future__ import annotations

WORK_TYPES = ("유지보수", "임대", "운영", "구매", "공사", "연구", "고도화", "개발", "구축", "감리")

# 우선순위 순서대로 검사 — 한 제목에 여러 키워드가 겹치면 먼저 매칭되는 쪽을 채택한다
# (예: "유지보수"가 "구축"보다 더 구체적인 신호라 먼저 봄).
# 2026-09-21 — 고객 관심 신호(추천 알고리즘 비교, docs/의사결정_로그.md 192번)로 쓰기 위해
# "연구"를 신규 추가하고, 기존에 "개발"에 묶여있던 "고도화"를 별도 사업유형으로 분리했다
# (사용자 지시 — 신규 개발 vs 기존 시스템 고도화를 구분해서 보고 싶어함). 같은 날 후속 지시로
# "감리"도 추가 — 고객이 감리·구매처럼 "들어가면 오히려 감점해야 할" 사업유형을 지정할 수
# 있어야 해서(recommendation_signals.py의 +/중립/- 3단계 선호로 이어짐).
_RULES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("유지보수", ("유지보수", "하자보수", "보수")),
    ("임대", ("임대", "렌탈", "대여")),
    ("운영", ("운영", "위탁운영", "관제 용역", "청소용역", "안전점검")),
    ("감리", ("감리",)),
    ("구매", ("구매", "구입", "보급", "공급")),
    ("공사", ("공사", "신설", "증설", "리모델링", "개보수")),
    ("연구", ("연구", "R&D", "연구개발")),
    ("고도화", ("고도화",)),
    ("개발", ("개발", "개선")),
    ("구축", ("구축", "도입", "설치")),
)

# 업무구분(나라장터 API가 직접 주는 값, notice.biz_type) — work_type과 별도 축이지만 고객이
# "관심 사업유형"을 고를 때는 하나로 합쳐서 보여준다(2026-09-21, 원래 요청에 물품·용역이
# 있었는데 처음 구현 때 누락됐던 부분). "공사"는 WORK_TYPES에 이미 있어 중복 제외.
BIZ_TYPES = ("물품", "용역", "외자")
WORK_TYPE_CATALOG = WORK_TYPES + BIZ_TYPES

# 고객이 사업유형마다 지정할 수 있는 선호 — 3단계 중 "중립"은 값 자체를 저장 안 함으로
# 표현한다(recommendation_signals.py의 work_type_signal 참고).
WORK_TYPE_PREFERENCES = ("positive", "negative")


def guess_work_type(title: str) -> str | None:
    for work_type, keywords in _RULES:
        if any(kw in title for kw in keywords):
            return work_type
    return None
