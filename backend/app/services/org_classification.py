# 이 한 글자는 다른 단어에도 흔히 섞여 있어(예: "수도"·"제도") 전체 문자열 부분일치로 보면
# 오탐이 심하다 — 공백으로 나눈 마지막 토큰이 이 글자로 "끝나는지"만 본다(그 토큰 자체가
# 행정구역명일 때만 해당, 뒤에 "상하수도사업소"처럼 하위기관명이 더 붙으면 그 하위기관명이
# 마지막 토큰이 되어 여기 안 걸리고 위쪽 더 구체적인 규칙(에너지환경 등)에 넘어간다).
_ADMIN_UNIT_SUFFIXES = ("도", "시", "군", "구")


def classify_org_category(name: str) -> str | None:
    """기관명 패턴으로 분야를 하나 고른다. 못 고르면 None(미분류로 남김 — 억지 분류 금지)."""
    for category, keywords in ORG_CATEGORY_RULES:
        if any(keyword in name for keyword in keywords):
            return category
    tokens = name.split()
    if tokens and len(tokens[-1]) >= 2 and tokens[-1].endswith(_ADMIN_UNIT_SUFFIXES):
        return "지방행정"
    return None


def backfill_org_categories(conn: Connection) -> dict[str, int]:
    """이미 수집된 기관 중 category가 비어있는 행에 일괄 적용한다(2026-09-11, 1회성 백필 —
    이후 신규 기관은 _get_or_create_org()가 생성 시점에 바로 분류한다). 관리자가 이미
    수동으로 지정해둔 category(있다면)는 덮어쓰지 않는다 — 사람의 직접 판단 보존."""
    rows = conn.execute(select(org.c.id, org.c.name).where(org.c.category.is_(None))).all()
    counts: dict[str, int] = {}
    for org_id, name in rows:
        category = classify_org_category(name)
        if category is None:
            continue
        conn.execute(update(org).where(org.c.id == org_id).values(category=category))
        counts[category] = counts.get(category, 0) + 1
    return counts
